print("Добрый день!Введите первый элемент геометрической прогрессии")
b=int(input())
print("Введите множитель геометрической прогрессии")
q=int(input())
print("Введите номер последнего элемента")
n=int(input())
s=b*(q**n-1)//(q-1)
if -10_000 <= b <= 10_000 and 1 <= q <= 50 and 2 <= n <= 100 :
    print("Результат вычисления суммы геометрической прогрессии",s)
else :
    print ("Ошибочное значение")