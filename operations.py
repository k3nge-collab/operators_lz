n = int(input("Введите число от 1 до 100000: "))
if n >= 1 and n <= 100000: # Проверяем  число 
    c= 0 # Счётчик операций
    while n > 0: # Пока число больше 0, отнимаем 3 и считаем шаги
        n = n - 3 #Выполняется
        c = c + 1 #Cчетчик увеличивается
    print(c)# Выводим результат (количество операций)
else:
    print("Число не подходит")